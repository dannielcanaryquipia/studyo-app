/**
 * generate-frame-paths.js
 * Reads every unique_frame_NNNN.svg from ./frames/, extracts the path `d`
 * attribute from each, and writes ../frame-paths.ts.
 *
 * Run from this directory:
 *   node generate-frame-paths.js
 *
 * Re-run any time an SVG in ./frames/ is updated.
 */
const fs = require('fs');
const path = require('path');

const framesDir = path.join(__dirname, 'frames');
const outFile = path.join(__dirname, 'frame-paths.ts');

// Sort numerically by the 4-digit suffix (e.g. 0001 < 0010).
const files = fs
  .readdirSync(framesDir)
  .filter((f) => f.match(/^unique_frame_\d+\.svg$/i))
  .sort((a, b) => {
    const na = parseInt(a.match(/\d+/)[0], 10);
    const nb = parseInt(b.match(/\d+/)[0], 10);
    return na - nb;
  });

if (files.length === 0) {
  console.error('No SVG files found in', framesDir);
  process.exit(1);
}

const paths = files.map((file) => {
  const svg = fs.readFileSync(path.join(framesDir, file), 'utf8');
  const match = svg.match(/\sd="([^"]*)"/);
  return match ? match[1] : '';
});

const durationMs = Math.round((files.length / 30) * 1000);
let out = `// AUTO-GENERATED by generate-frame-paths.js — do not edit by hand.\n`;
out += `// Source: assets/onboarding/frames/unique_frame_NNNN.svg (${files.length} files @ 30fps = ${durationMs} ms)\n`;
out += `// Re-generate: node assets/onboarding/generate-frame-paths.js\n`;
out += `export const SPLASH_FRAME_PATHS: readonly string[] = [\n`;
paths.forEach((d, i) => {
  out += `  ${JSON.stringify(d)}, // frame ${String(i + 1).padStart(4, '0')} — ${files[i]}\n`;
});
out += `] as const;\n`;

const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
if (prev === out) {
  console.log('frame-paths.ts already up to date.');
} else {
  fs.writeFileSync(outFile, out);
  console.log(`Wrote ${files.length} frames → frame-paths.ts (${Math.round(Buffer.byteLength(out) / 1024)} KB)`);
}
